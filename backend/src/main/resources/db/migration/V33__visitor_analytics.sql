-- Anonymous website visits, shown to platform admins only. Purged after 90 days. ---------------------------------
CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE analytics.visits (
    id          UUID PRIMARY KEY,                 -- generated by the browser so a retried beacon cannot double count
    visitor_id  UUID NOT NULL,
    session_id  UUID NOT NULL,
    tenant_id   UUID REFERENCES core.tenants(id) ON DELETE SET NULL,
    host        VARCHAR(255) NOT NULL,
    path        VARCHAR(500) NOT NULL,
    query       VARCHAR(500),
    referrer    VARCHAR(500),
    ip          VARCHAR(64),
    country     VARCHAR(8),
    city        VARCHAR(100),
    user_agent  VARCHAR(500),
    browser     VARCHAR(40),
    os          VARCHAR(40),
    device_type VARCHAR(10) NOT NULL DEFAULT 'desktop',
    language    VARCHAR(20),
    timezone    VARCHAR(64),
    screen_w    INTEGER,
    screen_h    INTEGER,
    viewed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    duration_ms INTEGER
);
CREATE INDEX visits_viewed_at_idx ON analytics.visits (viewed_at DESC);
CREATE INDEX visits_visitor_idx ON analytics.visits (visitor_id, viewed_at DESC);
CREATE INDEX visits_tenant_idx ON analytics.visits (tenant_id, viewed_at DESC);

INSERT INTO core.permissions (code, name) VALUES ('platform.analytics.read', 'View website visitors (platform)');
INSERT INTO core.role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM core.roles r, core.permissions p
WHERE r.code IN ('PLATFORM_OWNER','PLATFORM_ADMIN') AND r.tenant_id IS NULL AND p.code = 'platform.analytics.read'
ON CONFLICT DO NOTHING;
