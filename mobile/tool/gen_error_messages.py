"""Adds the new error messages (new_errors.py) to web/lib/messages.ts, then writes the same messages for the Flutter apps.
Run from anywhere:  python3 mobile/tool/gen_error_messages.py   (safe to run again)"""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
sys.path.insert(0, here)
from new_errors import NEW, FIELDS, RULES   # noqa: E402

msgs_path = os.path.join(root, 'web/lib/messages.ts')
s = open(msgs_path, encoding='utf-8').read()
q = lambda v: json.dumps(v, ensure_ascii=False)
RULE_KEYS = {'rule.required': ('is required', 'مطلوب'), 'rule.length': ('must be {a} to {b} characters', 'يجب أن يكون من {a} إلى {b} حرفًا'), 'rule.email': ('is not a valid email', 'بريد إلكتروني غير صحيح'),
             'rule.min': ('must be at least {a}', 'يجب ألا يقل عن {a}'), 'rule.max': ('must be at most {a}', 'يجب ألا يزيد عن {a}'), 'rule.format': ('has an invalid format', 'الصيغة غير صحيحة'), 'rule.invalid': ('is not valid', 'غير صحيح')}
entries_en, entries_ar = [], []
for code, (en, ar) in NEW.items():
    entries_en.append((f'error.{code}', en)); entries_ar.append((f'error.{code}', ar))
for f, (en, ar) in FIELDS.items():
    entries_en.append((f'field.{f}', en)); entries_ar.append((f'field.{f}', ar))
for k, (en, ar) in RULE_KEYS.items():
    entries_en.append((k, en)); entries_ar.append((k, ar))

anchor = r'  "error\.generic": "[^"]*",\n'
ms = list(re.finditer(anchor, s))
assert len(ms) == 2, 'expected the en and ar error.generic lines'
# keys already defined per dictionary: split the file at the second anchor
split = ms[1].start()
en_part, ar_part = s[:split], s[split:]
def add_block(part, entries, which):
    have = set(re.findall(r'^  "([^"]+)":', part, re.M))
    block = ''.join(f'  {q(k)}: {q(v)},\n' for k, v in entries if k not in have)
    m = re.search(anchor, part)
    return part[:m.end()] + block + part[m.end():]
s = add_block(en_part, entries_en, 'en') + add_block(ar_part, entries_ar, 'ar')
open(msgs_path, 'w', encoding='utf-8').write(s)

# ---- Flutter: every error.* / field.* / rule.* pair, Arabic first
second = list(re.finditer(anchor, s))[1].start()
def pairs(part):
    return {m.group(1): json.loads('"' + m.group(2) + '"') for m in re.finditer(r'^  "((?:error|field|rule)\.[^"]+)": "((?:[^"\\]|\\.)*)",?$', part, re.M)}
en, ar = pairs(s[:second]), pairs(s[second:])
out = ["// GENERATED by mobile/tool/gen_error_messages.py from web/lib/messages.ts - do not edit by hand.\n",
       "/// error code -> [arabic, english]; {max}, {types}, {detail} are filled in from the server's answer.\n",
       "const Map<String, List<String>> kErrorMessages = {\n"]
for k in sorted(en):
    if k.startswith('error.') and k in ar:
        out.append(f"  {q(k[6:])}: [{q(ar[k])}, {q(en[k])}],\n".replace('$', r'\$'))
out.append("};\n\nconst Map<String, List<String>> kFieldNames = {\n")
for k in sorted(en):
    if k.startswith('field.') and k in ar:
        out.append(f"  {q(k[6:])}: [{q(ar[k])}, {q(en[k])}],\n")
out.append("};\n\nconst Map<String, List<String>> kRuleTexts = {\n")
for k in sorted(en):
    if k.startswith('rule.') and k in ar:
        out.append(f"  {q(k[5:])}: [{q(ar[k])}, {q(en[k])}],\n")
out.append("};\n")
open(os.path.join(root, 'mobile/packages/platform_core/lib/src/error_messages.g.dart'), 'w', encoding='utf-8').write(''.join(out))
print('web keys added; flutter map:', len([k for k in en if k.startswith('error.')]), 'errors')
