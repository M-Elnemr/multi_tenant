#!/usr/bin/env python3
"""Generates lib/core/strings.g.dart and lib/core/governorates.g.dart from the website's dictionaries (web/lib/messages.ts, web/lib/governorates.ts)
so the app and the website say the same thing. Run from mobile/apps/open: python3 tool/gen_strings.py"""
import json, re, os
root = os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", "web", "lib")
src = open(os.path.join(root, "messages.ts"), encoding="utf8").read()

def grab(name):
    st = src.index(f"const {name}:")
    body = src[st:src.index("\n};", st)]
    out = {}
    for m in re.finditer(r'^\s*("(?:[^"\\]|\\.)+"):\s*("(?:[^"\\]|\\.)*"),?\s*$', body, re.M):
        out[json.loads(m.group(1))] = json.loads(m.group(2))
    return out

en, ar = grab("en"), grab("ar")
EXTRA = ["brand.name", "shop.home", "nav.cart", "nav.account", "common.close", "common.cancel", "common.save", "common.loading", "common.retry"]
keys = [k for k in en if k.startswith("open.") or k.startswith("error.") or k in EXTRA]
def d(s): return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"
lines = ["// GENERATED by tool/gen_strings.py from web/lib/messages.ts - do not edit by hand.", "const Map<String, List<String>> kStrings = {"]
for k in keys:
    lines.append(f"  {d(k)}: [{d(en[k])}, {d(ar.get(k, en[k]))}],")
lines.append("};")
open(os.path.join(os.path.dirname(__file__), "..", "lib", "core", "strings.g.dart"), "w", encoding="utf8").write("\n".join(lines) + "\n")

g = open(os.path.join(root, "governorates.ts"), encoding="utf8").read()
rows = re.findall(r'\{ code: "(\w+)", ar: "([^"]+)", en: "([^"]+)" \}', g)
out = ["// GENERATED by tool/gen_strings.py from web/lib/governorates.ts.", "const List<({String code, String ar, String en})> kGovernorates = ["]
out += [f"  (code: {d(c)}, ar: {d(a)}, en: {d(e)})," for c, a, e in rows]
out.append("];")
open(os.path.join(os.path.dirname(__file__), "..", "lib", "core", "governorates.g.dart"), "w", encoding="utf8").write("\n".join(out) + "\n")
print(len(keys), "strings,", len(rows), "governorates")
